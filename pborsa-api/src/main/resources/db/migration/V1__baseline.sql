-- Initial schema for trading entities.

create table orders
(
    id                uuid         not null
        primary key,
    alpaca_order_id   varchar(255),
    cancelled_at      timestamp(6) with time zone,
    client_order_id   varchar(255),
    created_at        timestamp(6) with time zone,
    created_at_remote timestamp(6) with time zone,
    expired_at        timestamp(6) with time zone,
    extended_hours    boolean,
    filled_at         timestamp(6) with time zone,
    filled_quantity   numeric(38, 2),
    limit_price       numeric(38, 2),
    quantity          numeric(38, 2),
    side              varchar(255)
        constraint orders_side_check
            check ((side)::text = ANY ((ARRAY ['BUY'::character varying, 'SELL'::character varying])::text[])),
    status            varchar(255)
        constraint orders_status_check
            check ((status)::text = ANY
                   ((ARRAY ['ACCEPTED_BY_APP'::character varying, 'NEW'::character varying, 'PARTIALLY_FILLED'::character varying, 'FILLED'::character varying, 'DONE_FOR_DAY'::character varying, 'CANCELED'::character varying, 'EXPIRED'::character varying, 'REPLACED'::character varying, 'PENDING_CANCEL'::character varying, 'PENDING_REPLACE'::character varying, 'REJECTED'::character varying, 'PENDING_NEW'::character varying, 'ACCEPTED'::character varying, 'ACCEPTED_FOR_BIDDING'::character varying, 'STOPPED'::character varying, 'SUSPENDED'::character varying, 'CALCULATED'::character varying, 'HELD'::character varying])::text[])),
    stop_price        numeric(38, 2),
    submitted_at      timestamp(6) with time zone,
    symbol            varchar(255),
    time_in_force     varchar(255)
        constraint orders_time_in_force_check
            check ((time_in_force)::text = ANY
                   ((ARRAY ['DAY'::character varying, 'GTC'::character varying, 'OPG'::character varying, 'CLS'::character varying, 'IOC'::character varying, 'FOK'::character varying])::text[])),
    type              varchar(255)
        constraint orders_type_check
            check ((type)::text = ANY
                   ((ARRAY ['MARKET'::character varying, 'LIMIT'::character varying, 'STOP'::character varying, 'STOP_LIMIT'::character varying, 'TRAILING_STOP'::character varying])::text[])),
    updated_at        timestamp(6) with time zone,
    updated_at_remote timestamp(6) with time zone,
    user_id           varchar(255) not null,
    workflow_id       varchar(255)
);

create table order_history
(
    id         uuid         not null
        primary key,
    created_at timestamp(6) with time zone,
    message    varchar(512),
    status     varchar(255) not null
        constraint order_history_status_check
            check ((status)::text = ANY
                   ((ARRAY ['ACCEPTED_BY_APP'::character varying, 'NEW'::character varying, 'PARTIALLY_FILLED'::character varying, 'FILLED'::character varying, 'DONE_FOR_DAY'::character varying, 'CANCELED'::character varying, 'EXPIRED'::character varying, 'REPLACED'::character varying, 'PENDING_CANCEL'::character varying, 'PENDING_REPLACE'::character varying, 'REJECTED'::character varying, 'PENDING_NEW'::character varying, 'ACCEPTED'::character varying, 'ACCEPTED_FOR_BIDDING'::character varying, 'STOPPED'::character varying, 'SUSPENDED'::character varying, 'CALCULATED'::character varying, 'HELD'::character varying])::text[])),
    user_id    varchar(255) not null,
    order_id   uuid         not null
        constraint fk_order_history_order
            references orders
);

create table user_api_credentials
(
    id                   bigint generated by default as identity
        primary key,
    active               boolean                     not null,
    api_key_encrypted    varchar(255)                not null,
    created_at           timestamp(6) with time zone not null,
    paper_trading        boolean                     not null,
    secret_key_encrypted varchar(255)                not null,
    updated_at           timestamp(6) with time zone not null,
    user_id              varchar(255)                not null
        constraint idx_user_id
            unique
);
